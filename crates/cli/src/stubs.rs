//! Generating Python type stubs from module option declarations, so modules written as typed
//! Python can be checked by pyright before they run as Starlark.
//!
//! Every record becomes a `TypedDict`, and `Ctx.read` gets an overload per option path that
//! returns that option's type. A module reading `ctx.read("services.syncthing")` then gets
//! `dict[str, ServicesSyncthing]` without writing any annotations.

use std::collections::BTreeMap;
use std::fmt::Write;
use std::path::Path;

use distro_eval::{OptionPath, OptionSpec, Schema, Sources, Type};

use crate::system::{self, ModuleOrder};

/// The host API, which doesn't depend on the modules.
const HOST: &str = r#"
class Type: ...
class Option: ...

class _Types:
    bool: Type
    int: Type
    float: Type
    str: Type
    path: Type
    port: Type
    freeform: Type
    def list(self, item: Type, /) -> Type: ...
    def set(self, item: Type, /) -> Type: ...
    def ordered(self, item: Type, /) -> Type: ...
    def map(self, item: Type | Option, /) -> Type: ...
    def record(self, **fields: Type | Option) -> Type: ...
    def one_of(self, choices: list[str], /) -> Type: ...
    def range(self, min: int, max: int, /) -> Type: ...

types: _Types

def option(
    type: Type,
    /,
    *,
    default: Any = ...,
    optional: bool = ...,
    runtime: bool = ...,
    doc: str = ...,
) -> Option: ...

class _Formats:
    def json(self, value: Any, /) -> str: ...

formats: _Formats

def module(
    *,
    name: str,
    options: dict[str, Type | Option],
    writes: list[str],
    render: Callable[[Ctx], None],
) -> None: ...
"#;

/// Writes stubs for the modules in `modules` to `out`. With `check`, only compares, and reports
/// whether `out` is up to date.
pub fn write(modules: &Path, out: &Path, check: bool) -> Result<bool, String> {
    let mut sources = Sources::default();
    let loaded = system::load_modules(modules, &mut sources, ModuleOrder::Sorted)?;
    let mut schema = Schema::default();
    for module in &loaded {
        for (path, spec) in module.options() {
            schema
                .declare_at(&path, spec)
                .map_err(|e| format!("module `{}`: {e}", module.name()))?;
        }
    }
    let stubs = generate(&schema);
    if check {
        let up_to_date = std::fs::read_to_string(out).is_ok_and(|current| current == stubs);
        if !up_to_date {
            eprintln!(
                "{} is out of date; run `distro stubs --modules {}`",
                out.display(),
                modules.display()
            );
        }
        return Ok(up_to_date);
    }
    std::fs::write(out, stubs).map_err(|e| format!("{}: {e}", out.display()))?;
    Ok(true)
}

pub fn generate(schema: &Schema) -> String {
    let mut stubs = Stubs::default();
    let mut reads = Vec::new();
    if let Type::Record(record) = &schema.root().ty {
        for (name, field) in &record.fields {
            stubs.reads(&OptionPath::root().child(name.as_str()), field, &mut reads);
        }
    }

    let mut out = String::from(
        "# Generated by `distro stubs` from the modules' option declarations. Don't edit.\n\
         from typing import Any, Callable, Literal, NotRequired, TypedDict, overload\n",
    );
    out.push_str(HOST);
    for (name, fields) in &stubs.classes {
        // Writing to a String cannot fail.
        let _ = writeln!(out, "\n{name} = TypedDict(\"{name}\", {{");
        for (key, ty) in fields {
            let _ = writeln!(out, "    \"{key}\": {ty},");
        }
        out.push_str("})\n");
    }
    out.push_str("\nclass Ctx:\n");
    for (path, ty) in &reads {
        let _ = writeln!(
            out,
            "    @overload\n    def read(self, path: Literal[\"{path}\"], /) -> {ty}: ..."
        );
    }
    out.push_str(
        "    @overload\n    def read(self, path: str, /) -> Any: ...\n\
         \x20   def set(self, path: str, value: Any, /) -> None: ...\n\
         \x20   def default(self, path: str, value: Any, /) -> None: ...\n\
         \x20   def remove(self, path: str, items: list[Any], /) -> None: ...\n\
         \x20   def unit(self, name: str, sections: dict[str, dict[str, Any]], /) -> None: ...\n\
         \x20   def file(self, path: str, text: str, mode: int = ..., /) -> None: ...\n\
         \x20   def package(self, name: str, /) -> None: ...\n",
    );
    out
}

#[derive(Default)]
struct Stubs {
    /// `TypedDict` classes by name: field name to Python type.
    classes: BTreeMap<String, Vec<(String, String)>>,
}

impl Stubs {
    /// Adds a `read` overload for `path` and for every record field under it. Paths inside maps
    /// have names chosen by the configuration, so they fall back to the untyped overload.
    fn reads(&mut self, path: &OptionPath, spec: &OptionSpec, out: &mut Vec<(String, String)>) {
        let ty = self.python_type(path, &spec.ty);
        let ty = if may_be_unset(spec) {
            format!("{ty} | None")
        } else {
            ty
        };
        out.push((path.to_string(), ty));
        if let Type::Record(record) = &spec.ty {
            for (name, field) in &record.fields {
                self.reads(&path.child(name.as_str()), field, out);
            }
        }
    }

    /// The Python type for values of `ty` at `path`, defining `TypedDict`s for records on the way.
    fn python_type(&mut self, path: &OptionPath, ty: &Type) -> String {
        match ty {
            Type::Bool => "bool".into(),
            Type::Int { .. } => "int".into(),
            Type::Float => "float".into(),
            Type::Str | Type::Path => "str".into(),
            Type::Enum(choices) => {
                let choices: Vec<String> = choices.iter().map(|c| format!("\"{c}\"")).collect();
                format!("Literal[{}]", choices.join(", "))
            }
            Type::List { item, .. } => format!("list[{}]", self.python_type(path, item)),
            Type::Map(item) => format!("dict[str, {}]", self.python_type(path, &item.ty)),
            Type::Freeform => "Any".into(),
            Type::Record(record) => {
                let name = class_name(path);
                let mut fields = Vec::with_capacity(record.fields.len());
                for (field, spec) in &record.fields {
                    let ty = self.python_type(&path.child(field.as_str()), &spec.ty);
                    let ty = if may_be_unset(spec) {
                        format!("NotRequired[{ty}]")
                    } else {
                        ty
                    };
                    fields.push((field.clone(), ty));
                }
                self.classes.insert(name.clone(), fields);
                name
            }
        }
    }
}

/// Optional options without a default may have no value: `None` from `read`, and absent from the
/// record they're a field of.
fn may_be_unset(spec: &OptionSpec) -> bool {
    spec.optional && spec.default.is_none()
}

/// `services.syncthing` becomes `ServicesSyncthing`.
fn class_name(path: &OptionPath) -> String {
    path.segments()
        .iter()
        .flat_map(|segment| segment.split(|c: char| !c.is_ascii_alphanumeric()))
        .map(|word| {
            let mut chars = word.chars();
            chars
                .next()
                .map(|first| first.to_ascii_uppercase().to_string() + chars.as_str())
                .unwrap_or_default()
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use distro_eval::{ListMerge, OptionSpec, Schema, Type, Value};

    use super::generate;

    #[test]
    fn records_become_typed_dicts_and_paths_get_read_overloads() {
        let mut schema = Schema::default();
        let instance = Type::record([
            (
                "port",
                OptionSpec::new(Type::port()).default(Value::Int(8384)),
            ),
            ("root", OptionSpec::new(Type::Path).optional()),
            (
                "domains",
                OptionSpec::new(Type::list(Type::Str, ListMerge::Set)).default(Value::List(vec![])),
            ),
        ]);
        schema
            .declare(
                "services.web-app",
                OptionSpec::new(Type::map(OptionSpec::new(instance))),
            )
            .unwrap();
        schema
            .declare("system.hostname", OptionSpec::new(Type::Str))
            .unwrap();

        let stubs = generate(&schema);
        let generated = &stubs[stubs.find("\nServices = ").unwrap()..];
        insta::assert_snapshot!(generated, @r#"
        Services = TypedDict("Services", {
            "web-app": dict[str, ServicesWebApp],
        })

        ServicesWebApp = TypedDict("ServicesWebApp", {
            "domains": list[str],
            "port": int,
            "root": NotRequired[str],
        })

        System = TypedDict("System", {
            "hostname": str,
        })

        class Ctx:
            @overload
            def read(self, path: Literal["services"], /) -> Services: ...
            @overload
            def read(self, path: Literal["services.web-app"], /) -> dict[str, ServicesWebApp]: ...
            @overload
            def read(self, path: Literal["system"], /) -> System: ...
            @overload
            def read(self, path: Literal["system.hostname"], /) -> str: ...
            @overload
            def read(self, path: str, /) -> Any: ...
            def set(self, path: str, value: Any, /) -> None: ...
            def default(self, path: str, value: Any, /) -> None: ...
            def remove(self, path: str, items: list[Any], /) -> None: ...
            def unit(self, name: str, sections: dict[str, dict[str, Any]], /) -> None: ...
            def file(self, path: str, text: str, mode: int = ..., /) -> None: ...
            def package(self, name: str, /) -> None: ...
        "#);
    }
}
